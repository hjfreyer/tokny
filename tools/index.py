#!/usr/bin/env python3
"""Build grants/INDEX.md from the frontmatter of grants/*.md.

Usage: python3 tools/index.py [--check]

--check only validates frontmatter and exits non-zero on problems.
No dependencies; the frontmatter is flat key: value YAML.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRANTS = ROOT / "grants"

REQUIRED = ["title", "funder", "source", "url", "amount", "match",
            "deadline", "found", "status", "fit"]
STATUSES = {"candidate", "assessed", "pursuing", "applied", "awarded",
            "declined", "passed", "expired"}
FITS = {"unassessed", "poor", "possible", "good", "strong"}


def parse_frontmatter(text: str) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError("no frontmatter block")
    fm = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            raise ValueError(f"bad frontmatter line: {line!r}")
        k, v = line.split(":", 1)
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        fm[k.strip()] = v
    return fm


def load():
    rows, problems = [], []
    for path in sorted(GRANTS.glob("*.md")):
        if path.name == "INDEX.md":
            continue
        try:
            fm = parse_frontmatter(path.read_text())
        except ValueError as e:
            problems.append(f"{path.name}: {e}")
            continue
        for k in REQUIRED:
            if k not in fm:
                problems.append(f"{path.name}: missing {k}")
        if fm.get("status") not in STATUSES:
            problems.append(f"{path.name}: bad status {fm.get('status')!r}")
        if fm.get("fit") not in FITS:
            problems.append(f"{path.name}: bad fit {fm.get('fit')!r}")
        src = fm.get("source", "")
        if src and not (ROOT / "sources" / f"{src}.md").exists():
            problems.append(f"{path.name}: source {src!r} has no sources/ file")
        fm["_slug"] = path.stem
        rows.append(fm)
    return rows, problems


def deadline_key(r):
    d = r.get("deadline", "") or ""
    if re.match(r"\d{4}-\d{2}-\d{2}", d):
        return (0, d)
    if d == "rolling":
        return (1, "")
    return (2, d)


def render(rows):
    out = ["# Grant index", "",
           f"{len(rows)} opportunities. Generated by `tools/index.py`; "
           "do not edit by hand.", ""]
    by_status = {}
    for r in rows:
        by_status.setdefault(r["status"], []).append(r)
    order = ["pursuing", "applied", "assessed", "candidate", "awarded",
             "declined", "passed", "expired"]
    for st in order:
        group = by_status.get(st)
        if not group:
            continue
        out += [f"## {st} ({len(group)})", "",
                "| deadline | title | funder | amount | match | fit |",
                "|---|---|---|---|---|---|"]
        for r in sorted(group, key=deadline_key):
            out.append(
                f"| {r.get('deadline') or ''} "
                f"| [{r['title']}]({r['_slug']}.md) "
                f"| {r['funder']} | {r.get('amount','')} "
                f"| {r.get('match','')} | {r['fit']} |")
        out.append("")
    return "\n".join(out)


def main():
    rows, problems = load()
    for p in problems:
        print("PROBLEM:", p, file=sys.stderr)
    if "--check" in sys.argv:
        sys.exit(1 if problems else 0)
    (GRANTS / "INDEX.md").write_text(render(rows))
    print(f"wrote grants/INDEX.md ({len(rows)} rows, {len(problems)} problems)")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
